package Arithmetic_Operators;

public class Arithmetic {
	public static void main(String[] args) {
		
	int i = 239;
	int j = 4848;
		
	
	// Addition Operator
	
	System.out.println("The addition of " + i + " & " + j + " is : " + (i + j));
	
	
	// Subtraction Operator
	
	System.out.println("The Subtraction of " + i + " & " + j + " is : " + (i - j));
	
	
	// Multiplication Operator 
	
	System.out.println("The Multiplication of " + i + " & " + j + " is : " + (i * j));
	
	
	
	
	
	System.out.println("The Division  of " + i + " & " + j + " is : " + (i / j));
	
	
	
	
	
	System.out.println("The Modulous of " + i + " & " + j + " is : " + (i % j));
	
	
	
	
	//System.out.println("The addition of " + i + " & " + j + " is : " + (i + j));
	}
	
	
	
}
