package ProgramsOnIf;
//to check a given Number is between 10 and 50 using Logical
public class Task1 {

	public static void main(String[] args) {
		int n = 50;
		
		System.out.println("--------To check a given Number is between 10 and 50 using Logical --------");
		if(n >= 10 && n<= 50)
		{
			System.out.println("The Given Number is Between 10 and 50.");
		}
		else {
			System.out.println("The Given Number is not Between 10 and 50.");
		}
	}
}
